//! Safe Mode (раздел VII плана): если пользователь держит Shift во время
//! запуска Launcher'а, пропускается проверка обновлений и запускается
//! последняя известная рабочая версия как есть, с диагностикой в
//! `recovery.log` — путь восстановления, если что-то системно сломалось.

/// `true`, если левая или правая клавиша Shift зажата в момент вызова.
#[cfg(windows)]
pub fn is_shift_held() -> bool {
    use windows::Win32::UI::Input::KeyboardAndMouse::{GetAsyncKeyState, VK_SHIFT};

    // SAFETY: GetAsyncKeyState — стандартный, не требующий очистки вызов
    // WinAPI; VK_SHIFT — валидный виртуальный код клавиши.
    let state = unsafe { GetAsyncKeyState(VK_SHIFT.0 as i32) };
    // Старший бит установлен, если клавиша нажата в данный момент.
    (state as u16 & 0x8000) != 0
}

#[cfg(all(test, windows))]
mod tests {
    use super::*;

    #[test]
    fn does_not_panic_when_called() {
        // Не можем детерминированно эмулировать нажатие клавиши в
        // автоматическом тесте — проверяем только, что вызов безопасен и
        // возвращает булево значение без паники (реальная проверка "Shift
        // действительно пропускает проверку обновлений" — часть Фазы 8,
        // ручное тестирование).
        let _ = is_shift_held();
    }
}
