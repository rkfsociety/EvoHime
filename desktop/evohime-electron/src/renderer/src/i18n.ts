let activeLocale: AppLocale = 'ru'
const listeners = new Set<() => void>()

export function setAppLocale(locale: AppLocale): void {
  const changed = activeLocale !== locale
  activeLocale = locale
  if (typeof document !== 'undefined') document.documentElement.lang = locale
  if (typeof window !== 'undefined') window.evohime?.v1.setLocale(locale)
  if (!changed) return
  for (const listener of listeners) listener()
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

export function useAppLocale(): AppLocale {
  return useSyncExternalStore(subscribe, () => activeLocale, () => 'ru')
}

export function useT(): (text: string) => string {
  const locale = useAppLocale()
  return (text) => translate(text, locale)
}

export function translate(text: string, locale?: AppLocale): string
export function translate<T>(value: T, locale?: AppLocale): T
export function translate(value: unknown, locale = activeLocale): unknown {
  if (typeof value !== 'string' || locale !== 'en') return value
  return ENGLISH[value] ?? value
}

export function formatDateTime(date: Date | number): string {
  return new Intl.DateTimeFormat(activeLocale === 'en' ? 'en-US' : 'ru-RU', {
    dateStyle: 'medium',
    timeStyle: 'short'
  }).format(date)
}

export function formatTime(date: Date | number): string {
  return new Intl.DateTimeFormat(activeLocale === 'en' ? 'en-US' : 'ru-RU', {
    hour: '2-digit',
    minute: '2-digit'
  }).format(date)
}

export function formatNumber(value: number): string {
  return new Intl.NumberFormat(activeLocale === 'en' ? 'en-US' : 'ru-RU').format(value)
}
